"""
Extra structure on the vertices: which are defined over F_p, and which carry a Z[i]-action of Weil type.

Frobenius. For A over F_{p^2} let A^(p) be its Frobenius twist. Since E0 is defined over F_p, with Frobenius the
endomorphism j (j^2 = -p), f -> f^(p) identifies L = Hom(E0, A) with Hom(E0, A^(p)), and

    (f a)^(p) = f^(p) (j a j^-1),    h(f^(p), g^(p)) = j h(f, g) j^-1.

So the lattice of A^(p) is j L j^-1 (conjugation by j in every slot; j normalises O). A vertex is defined over F_p
(its field of moduli is F_p, and over a finite field that is a field of definition) iff j L j^-1 is isomorphic to L.
A -> A^(p) is an involution of the vertex set and an automorphism of the isogeny graph; F_p-vertices are its fixed
points. For g = 1 these are the supersingular j in F_p.

Weil structures. A Z[i]-action on (A, lambda) compatible with the polarisation (Rosati acting as complex conjugation)
is an automorphism J of the vertex with J^2 = -1. Its type (a, b) is how i acts on the tangent space Lie(A): for
L = Hom(E0, A) we have Lie(A) = L / L j as a vector space over F_{p^2} = O / jO, on which i in O acts as a primitive
fourth root of unity, so a = dim ker(J - i) and b = dim ker(J + i) there (up to swapping a and b). Weil type means
(g/2, g/2). The Weil structures on a vertex are the conjugacy classes of such J in Aut(A, lambda).

Each Weil structure has a type I or II, read off from the Weil pairing omega on A[2]: the form
beta(x, y) = omega(x, J y) is symmetric (J preserves omega and J^2 = -1 = 1 on A[2]), so its diagonal
x -> omega(x, J x) is linear over F_2. Type I if it vanishes (beta alternating), type II otherwise. The two types
behave differently in the graph of Weil type fourfolds (isogeny_graph with structure = J): a type I vertex has 151
J-stable Lagrangians and a type II vertex 39. (E0^4 with the rotation of rotation_structure is of type I.)

Sources. The Frobenius twist and the Weil structures are standard notions; the formulas for them on L, the type I /
II split and the counts above are our own derivations and computations, not taken from the literature (see
REFERENCES.md).

So, the pattern is:

    1. frobenius_twist(L) = j L j^-1, and the vertex it is isomorphic to
    2. For each vertex, the elements J of Aut with J^2 = -1, and their type on L / L j
    3. Keep the Weil type ones up to conjugation, and record for each its type I / II from the Weil pairing on A[2]
"""

from sage.all import GF, ZZ, block_diagonal_matrix, identity_matrix, matrix

from lattice import HermitianLattice
from torsion import Frame


# ============================================================
# Frobenius
# ============================================================


def conjugation_matrix(ambient, a):
    """
    The matrix of x -> a x a^-1 (in every slot) on flat coordinates (rows)
    """
    ring = ambient.ring
    block = matrix([ring.coordinates(a * b * a**-1) for b in ring.O.basis()])
    assert block.denominator() == 1, "a does not normalise O"
    return block_diagonal_matrix([block] * ambient.g)


def frobenius_twist(L):
    """
    The lattice of the Frobenius twist A^(p): j L j^-1, with the same scale
    """
    return HermitianLattice(L.ambient, L.M * conjugation_matrix(L.ambient, L.ambient.ring.j), L.scale)


def frobenius_map(vertices):
    """
    For each vertex the index of its Frobenius twist (an involution of the vertex set)
    """
    out = []
    for L in vertices.lattices:
        w, new, _ = vertices.index(frobenius_twist(L))
        assert not new, "the twist of a vertex is not in the graph"
        out.append(w)
    assert all(out[out[v]] == v for v in range(len(out))), "Frobenius is not an involution"
    return out


