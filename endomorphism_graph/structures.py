# Weil structures
# ============================================================


def rotation_structure(ambient):
    """
    The Z[i]-action J (x_1, x_2, x_3, x_4, ...) -> (-x_2, x_1, -x_4, x_3, ...) on E0^g (g even), as a matrix on flat
    coordinates (rows). It is O-linear, preserves h, squares to -1 and has type (g/2, g/2): the starting point of the
    graph of Weil type varieties.
    """
    g = ambient.g
    assert g % 2 == 0
    R = matrix(ZZ, 4 * g, 4 * g)
    one = identity_matrix(ZZ, 4)
    for k in range(0, g, 2):
        R.set_block(4 * k, 4 * (k + 1), one)        # new slot k + 1 = old slot k
        R.set_block(4 * (k + 1), 4 * k, -one)       # new slot k = -old slot k + 1
    return R


def conjugation_orbit(X, generators):
    """
    The orbit of the matrix X under conjugation by the group generated by the invertible integer matrices
    generators. Returns a dictionary {s X s^-1 as a tuple: s} with one conjugator s for every element of the orbit,
    and the Schreier generators of the centraliser of X (as tuples), which generate it.
    """
    one = X.parent().identity_matrix()
    pairs = [(s, s.inverse().change_ring(ZZ)) for s in generators]
    conjugator = {tuple(X.list()): one}
    frontier, schreier = [(X, one)], set()
    while frontier:
        new = []
        for C, t in frontier:
            for s, s_inverse in pairs:
                D = s * C * s_inverse
                key = tuple(D.list())
                if key in conjugator:
                    z = conjugator[key].inverse().change_ring(ZZ) * s * t  # fixes X
                    if z != one:
                        schreier.add(tuple(z.list()))
                else:
                    conjugator[key] = s * t
                    new.append((D, s * t))
        frontier = new
    return conjugator, schreier


def lie_algebra_type(L, J):
    """
    The type (a, b) of J (J^2 = -1, O-linear) on Lie(A) = L / L j: a = dim ker(J - i), b = dim ker(J + i) over
    F_{p^2}
    """
    ambient = L.ambient
    ring = ambient.ring
    p, n = ring.p, J.nrows()
    F = GF(p)
    U = L.column_matrix(ambient.right(ring.j)).change_ring(F)  # columns span L j / pL inside L / pL
    annihilator = U.transpose().right_kernel_matrix()           # linear forms vanishing on L j
    assert annihilator.nrows() == n // 2
    R_i = L.column_matrix(ambient.right(ring.i))
    dims = []
    for sign in (1, -1):
        A = (J - sign * R_i).change_ring(F)
        preimage = (annihilator * A).right_kernel().dimension()  # x with (J -+ i) x in L j
        dims.append((preimage - n // 2) // 2)
    return tuple(dims)


def weil_class_type(L, J):
    """
    Type I if x -> omega(x, J x) vanishes on A[2] (beta alternating), type II otherwise
    """
    frame = Frame(L, 2)
    g = frame.g
    images = frame.action(J)
    omega = lambda u, v: sum(u[r] * v[g + r] - u[g + r] * v[r] for r in range(g)) % 2
    return "I" if all(omega(images[r], tuple(int(k == r) for k in range(2 * g))) == 0 for r in range(2 * g)) else "II"


def weil_structures(vertices, idx):
    """
    The Weil structures on the vertex: conjugacy classes of J in Aut with J^2 = -1 of type (g/2, g/2), as a sorted
    list of their types ("I" or "II")
    """
    L = vertices.lattices[idx]
    g = L.ambient.g
    if g % 2:
        return []
    n = 4 * g
    minus_one = -identity_matrix(ZZ, n)
    candidates = [J for J in vertices.automorphism_group(idx)
                  if J * J == minus_one and lie_algebra_type(L, J) == (g // 2, g // 2)]
    seen, types = set(), []
    for J in candidates:  # one type per conjugacy class
        if tuple(J.list()) in seen:
            continue
        orbit, _ = conjugation_orbit(J, vertices.generators[idx])
        seen.update(orbit)
        types.append(weil_class_type(L, J))
    return sorted(types)


# ============================================================
# The kernels at a vertex with a Weil structure
# ============================================================


def kernel_classifier(frame, J):
    """
    For a Z[i]-action J of a vertex, the function k -> |K cap A[1 + i]| on the Lagrangians K = frame.lagrangians[k],
    where A[1 + i] is the kernel of 1 + J on A[ell]. For a Weil type fourfold and ell = 2 the J-stable Lagrangians
    of a type I vertex split as 120 with |K cap A[1 + i]| = 4 (they factor through a middle variety: the middle
    steps), 30 with 8, and K = A[1 + i] itself (16, the endomorphism 1 + i, a loop).
    """
    F = frame.basis.base_ring()
    J_on_A = matrix(F, [list(image) for image in frame.action(J)])  # rows: images of the frame basis
    one_plus_i = (J_on_A + 1).left_kernel()
    ell = F.characteristic()

    def size(k):
        K = matrix(F, frame.lagrangians.bases[k]).row_space()
        return int(ell ** K.intersection(one_plus_i).dimension())

    return size
